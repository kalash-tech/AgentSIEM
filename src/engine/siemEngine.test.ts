test('clean resume produces nominal case with zero rule hits and low anomaly', () => {
  const clean = RESUME_SCENARIOS[0];
  const result = simulateHrBotTrace({
    traceId: 'case_test_clean',
    fileName: clean.fileName,
    content: clean.content,
    rules: INITIAL_RULES,
    vectorSignatures: INITIAL_VECTORS,
    baseline: DEFAULT_BASELINE,
  });

  assert.equal(result.status, 'NOMINAL');
  assert.equal(result.events.length, 3);
  assert.equal(result.ruleHits.length, 0);
  assert.equal(result.anomaly.isAnomaly, false);
  assert.equal(result.vectorMatch.isMatch, false);
});

