import React from 'react';
import type { AgentCase, SecurityRule, VectorSignature } from '../engine/types';

interface KpiStripProps {
  cases: AgentCase[];
  rules: SecurityRule[];
  vectors: VectorSignature[];
}

export const KpiStrip: React.FC<KpiStripProps> = ({ cases, rules, vectors }) => {
  const blockedCount = cases.filter(
    (c) => c.status === 'ALERT_BLOCKED' || c.status === 'RESOLVED'
  ).length;
  const activeRulesCount = rules.filter((r) => r.enabled).length;
  const autoRulesCount = rules.filter((r) => r.source === 'Gemini Auto-Rule').length;

  const metrics = [
    {
      label: 'Cases Monitored',
      value: cases.length,
      detail: `${cases.filter((c) => c.status === 'NOMINAL').length} nominal traces`,
    },
    {
      label: 'Threats Intercepted',
      value: blockedCount,
      detail: 'Paused before data egress',
      emphasis: blockedCount > 0 ? 'text-red-400' : 'text-white',
    },
    {
      label: 'Active Guard Rules',
      value: activeRulesCount,
      detail: `${autoRulesCount} generated by Gemini`,
    },
    {
      label: 'Vector Signatures',
      value: vectors.length,
      detail: 'k-NN injection index',
    },
  ];

  return (
    <section
      aria-label="Security overview metrics"
      className="grid grid-cols-1 divide-y divide-zinc-800 rounded-xl border border-zinc-800 bg-zinc-950 sm:grid-cols-2 sm:divide-y-0 lg:grid-cols-4 lg:divide-x"
    >
      {metrics.map((metric, idx) => (
        <div
          key={metric.label}
          className={`px-5 py-4 ${
            idx < 2 ? 'sm:border-b sm:border-zinc-800 lg:border-b-0' : ''
          } ${idx % 2 === 0 ? 'sm:border-r sm:border-zinc-800 lg:border-r-0' : ''}`}
        >
          <div className="text-xs font-medium text-zinc-400">{metric.label}</div>
          <div
            className={`mt-1.5 font-display text-2xl font-bold tracking-tight tabular-nums ${
              metric.emphasis ?? 'text-white'
            }`}
          >
            {metric.value}
          </div>
          <div className="mt-1 text-xs text-zinc-500 tabular-nums">{metric.detail}</div>
        </div>
      ))}
    </section>
  );
};
